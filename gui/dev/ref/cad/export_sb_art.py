"""Write the Stealthburner CAD block into gui/js/art.js.

    python3 export_sb_art.py [sb_outlines.json]

sb_outlines.json comes from build_stealthburner.py. Only the standard library
is needed. The block sits between the SB-BEGIN / SB-END markers in art.js.
"""
import json, os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ART = os.path.join(HERE, '..', '..', '..', 'js', 'art.js')
TONES = ['hi', 'lt', 'md', 'dk', 'dd', 'xd']
o = json.load(open(sys.argv[1] if len(sys.argv) > 1 else os.path.join(HERE, 'sb_outlines.json')))
items = []
for r in o['regions']:
    if r['layer'] in ('logo', 'fan'):
        continue
    items.append(r['layer'] + str(TONES.index(r['tone'])) + r['d'])
js = ('/* SB-BEGIN (generated by dev/ref/cad/export_sb_art.py from the Voron Stealthburner CW2 assembly; do not edit by hand)\n'
      ' * %s\n' % o['source'] +
      ' * GUI units: %s per mm, x 80 = filament/nozzle axis, y 210 = nozzle tip. */\n' % o['scale_units_per_mm'] +
      '  var SB = {\n' +
      '    aura: %s,\n' % json.dumps(o['aura']) +
      '    win: %s,\n' % json.dumps(o['fan_window']) +
      '    logo: %s,\n' % json.dumps(o['logo']) +
      '    glow: %s,\n' % json.dumps(o['glow']) +
      '    fan: %s,\n' % json.dumps(o['fan']) +
      '    tube: %s,\n' % json.dumps(o['tube']) +
      '    air: %s,\n' % json.dumps(o['air']) +
      '    edge: %s,\n' % json.dumps(o.get('edge') or {}, separators=(',', ':')) +
      '    r: [\n      ' + ',\n      '.join(json.dumps(x) for x in items) + '\n    ]\n  };\n' +
      '  /* SB-END */')
s = open(ART).read()
s2, n = re.subn(r'/\* SB-BEGIN.*?/\* SB-END \*/', lambda m: js, s, flags=re.S)
if n != 1:
    sys.exit('SB markers not found in art.js')
open(ART, 'w').write(s2)
print('wrote %d regions, %d bytes' % (len(items), len(js)))
