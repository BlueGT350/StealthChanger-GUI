"""Write the Anthead CAD blocks into ../../../js/art.js.

    python3 export_art.py outlines.json

The CAD block keeps the assembled Anthead + Orbiter trace (the default look).
CAD.head / CAD.headAura are the cowl without the Orbiter, and the ORB block is
the Orbiter on its own, so another extruder can take that space and the
Orbiter can sit on another head. Same outlines, split by part name.
"""
import json, os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ART = os.path.join(HERE, '..', '..', '..', 'js', 'art.js')
TONES = ['hi', 'lt', 'md', 'dk', 'dd', 'xd']
ORB = {
    'Bearings', 'Collet_Clip_', 'HubHousing_V5_With_Logo', 'LDO_36STH17_1004AHG_v6',
    'Latch_1_', 'Nuts_Bolts', 'O2_SensorHousing_v4_2_MJF',
    'Orbiter_2_7_LDO_Molding_CaptiveTensioner_v10_v1', 'Orbiter_Spider_Shaft_v4',
    'TangleRing_v4_2_MJF',
}
o = json.load(open(sys.argv[1] if len(sys.argv) > 1 else os.path.join(HERE, 'outlines.json')))


def item(r):
    L = r['layer']
    if L in ('logo', 'fan'):
        return None
    if L == 'revo':
        L = 'y' if r['ymin'] >= 204 else 'm'
    return L + str(TONES.index(r['tone'])) + r['d']


items, head_items, orb_items = [], [], []
for r in o['regions']:
    it = item(r)
    if it is None:
        continue
    items.append(it)
    (orb_items if r['part'] in ORB else head_items).append(it)

def arr(xs):
    return '[\n      ' + ',\n      '.join(json.dumps(x) for x in xs) + '\n    ]'

js = ('/* CAD-BEGIN (generated by dev/ref/cad/export_art.py from the AntHead + Orbiter v2.5 CAD; do not edit by hand)\n'
      ' * GUI units: %s per mm, x 80 = filament/nozzle axis, y 210 = nozzle tip.\n'
      ' * r is the assembled Anthead + Orbiter. head is the cowl alone. */\n' % o['scale_units_per_mm'] +
      '  var CAD = {\n' +
      '    aura: %s,\n' % json.dumps(o['aura']) +
      '    headAura: %s,\n' % json.dumps(o['silhouette']['anthead']) +
      '    win: %s,\n' % json.dumps(o['fan_window']) +
      '    logo: %s,\n' % json.dumps(o['logo']) +
      '    revo: %s,\n' % json.dumps(o['silhouette']['revo']) +
      '    r: ' + arr(items) + ',\n' +
      '    head: ' + arr(head_items) + '\n  };\n' +
      '  /* CAD-END */')
orb = ('/* ORB-BEGIN (generated by dev/ref/cad/export_art.py; Orbiter v2.5 alone, Anthead mount; do not edit by hand) */\n'
       '  var ORB = {\n' +
       '    aura: %s,\n' % json.dumps(o['silhouette']['orbiter']) +
       '    r: ' + arr(orb_items) + '\n  };\n' +
       '  /* ORB-END */')
s = open(ART).read()
s2, n = re.subn(r'/\* CAD-BEGIN.*?/\* CAD-END \*/', lambda m: js, s, count=1, flags=re.S)
if n != 1:
    sys.exit('CAD markers not found in art.js')
s3, n = re.subn(r'/\* ORB-BEGIN.*?/\* ORB-END \*/', lambda m: orb, s2, count=1, flags=re.S)
if n != 1:
    sys.exit('ORB markers not found in art.js')
open(ART, 'w').write(s3)
print('wrote cad %d, head %d, orbiter %d' % (len(items), len(head_items), len(orb_items)))
