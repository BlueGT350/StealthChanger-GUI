"""Write the WW block of gui/js/art.js from ww_outlines.json.

    python3 export_ww_art.py
"""
import json, os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ART = os.path.join(HERE, '..', '..', '..', 'js', 'art.js')
TONES = ['hi', 'lt', 'md', 'dk', 'dd', 'xd']
o = json.load(open(sys.argv[1] if len(sys.argv) > 1 else os.path.join(HERE, 'ww_outlines.json')))
items = [r['layer'] + str(TONES.index(r['tone'])) + r['d'] for r in o['regions']]
js = ('/* WW-BEGIN (generated by dev/ref/cad/export_ww_art.py from Wristwatch BMG v3; do not edit by hand)\n'
      ' * bythorsthunder/Voron_Mods Wristwatch_Extruder_BMG @ 359b95fb7263, GPL-3.0.\n'
      ' * Same Anthead frame: 1.95 units/mm, filament axis x 80, mount contact y 74.2. */\n'
      '  var WW = {\n' +
      '    aura: %s,\n' % json.dumps(o['aura']) +
      '    tube: %s,\n' % json.dumps(o['tube']) +
      '    r: [\n      ' + ',\n      '.join(json.dumps(x) for x in items) + '\n    ]\n  };\n' +
      '  /* WW-END */')
s = open(ART).read()
s2, n = re.subn(r'/\* WW-BEGIN.*?/\* WW-END \*/', lambda m: js, s, count=1, flags=re.S)
if n != 1:
    sys.exit('WW markers not found in art.js')
open(ART, 'w').write(s2)
print('wrote %d wristwatch regions' % len(items))
